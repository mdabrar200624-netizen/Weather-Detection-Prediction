# ============================================================
# GOOGLE OAUTH CALLBACK - PKCE
# ============================================================

if "code" in st.query_params:

    auth_code = st.query_params.get("code")

    if auth_code:

        try:

            # ------------------------------------------------
            # Get the verifier generated by Supabase
            # ------------------------------------------------

            storage = PersistentPKCEStorage()

            # Supabase's Python SDK uses this storage key
            code_verifier_key = "supabase.auth.token-code-verifier"

            code_verifier = storage.get_item(
                code_verifier_key
            )

            # ------------------------------------------------
            # Some SDK versions use a slightly different
            # storage key. Check the stored values as fallback.
            # ------------------------------------------------

            if not code_verifier:

                stored_data = load_pkce_storage()

                for key, value in stored_data.items():

                    if "code-verifier" in key.lower():

                        code_verifier = value
                        break

            if not code_verifier:

                st.error(
                    "❌ Google authentication failed: "
                    "PKCE verifier was not found."
                )

                st.info(
                    "Please click Continue with Google again."
                )

                st.query_params.clear()

            else:

                # ------------------------------------------------
                # Exchange authorization code for session
                # ------------------------------------------------

                response = supabase.auth.exchange_code_for_session(
                    {
                        "auth_code": auth_code,
                        "code_verifier": code_verifier,
                        "redirect_to": redirect_url
                    }
                )

                if response.user:

                    st.session_state["user"] = response.user

                    # Remove Google OAuth URL
                    st.session_state.pop(
                        "google_oauth_url",
                        None
                    )

                    # Remove authorization code
                    st.query_params.clear()

                    st.rerun()

                else:

                    st.query_params.clear()

                    st.error(
                        "❌ Google authentication failed. "
                        "No user session was received."
                    )

        except Exception as e:

            st.query_params.clear()

            st.error(
                "❌ Google authentication failed."
            )

            st.code(str(e))


