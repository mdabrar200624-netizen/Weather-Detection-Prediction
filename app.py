def get_redirect_url():

    try:

        host = st.context.headers.get("Host", "")

        if (
            host.startswith("localhost")
            or host.startswith("127.0.0.1")
        ):
            return "http://localhost:8501"

        return "https://weather-detection-prediction.streamlit.app"

    except Exception:

        return "http://localhost:8501"


