PKCE_FILE = ".streamlit/pkce_storage.json"


def load_pkce_storage():
    """Load PKCE data from disk."""
    try:
        if os.path.exists(PKCE_FILE):
            with open(PKCE_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)

                if isinstance(data, dict):
                    return data

    except Exception:
        pass

    return {}


def save_pkce_storage(data):
    """Save PKCE data to disk."""
    try:
        os.makedirs(
            os.path.dirname(PKCE_FILE),
            exist_ok=True
        )

        with open(PKCE_FILE, "w", encoding="utf-8") as f:
            json.dump(data, f)

    except Exception:
        pass


class PersistentPKCEStorage:
    """
    Persistent storage used by Supabase PKCE.

    Unlike Streamlit session_state, this survives
    the OAuth redirect and Streamlit rerun.
    """

    def get_item(self, key):

        data = load_pkce_storage()

        return data.get(key)

    def set_item(self, key, value):

        data = load_pkce_storage()

        data[key] = value

        save_pkce_storage(data)

    def remove_item(self, key):

        data = load_pkce_storage()

        if key in data:
            del data[key]

        save_pkce_storage(data)


